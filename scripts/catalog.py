#!/usr/bin/env python3
"""Filesystem catalog for MkDocs nav and generated indexes."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re

H1_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
NAV_ORDER_RE = re.compile(r"<!--\s*nav_order:\s*(-?\d+)\s*-->")
SKIP_NAMES = frozenset({"AGENTS.md", "README.md", "CONTRIBUTING.md", "index.md"})
GENERATED_MARKER = "<!-- Generated by scripts/prepare-mkdocs.py. Do not edit. -->"

SECTIONS: tuple[tuple[str, str], ...] = (
    ("channels", "Channels"),
    ("resources", "Resources"),
    ("ad-templates", "Templates"),
    ("meta", "Meta"),
)

SECTION_INTROS: dict[str, str] = {
    "channels": "Guides for each major advertising channel, from setup through optimization.",
    "resources": "Cross-cutting topics that apply across channels.",
    "ad-templates": "Ad templates and design resources.",
    "meta": "Repository documentation and community policy.",
}

HOME_INTRO = """**A practical advertising playbook for small businesses.**

Awesome Ads is an open reference for planning, launching, and refining campaigns across digital and traditional channels. Each guide stands on its own: read cover to cover or jump straight to the channel you need."""

LICENSE_URL = "https://github.com/TMHSDigital/Awesome-Ads/blob/main/LICENSE"
AGENTS_URL = "https://github.com/TMHSDigital/Awesome-Ads/blob/main/AGENTS.md"


@dataclass(frozen=True)
class Page:
    rel: str
    title: str
    nav_order: int | None
    stem: str


def parse_page(path: Path, docs: Path) -> Page:
    text = path.read_text(encoding="utf-8")
    heading = H1_RE.search(text)
    if heading is None:
        raise ValueError(f"{path} has no H1")
    order_match = NAV_ORDER_RE.search(text)
    nav_order = int(order_match.group(1)) if order_match else None
    rel = path.relative_to(docs).as_posix()
    return Page(rel=rel, title=heading.group(1).strip(), nav_order=nav_order, stem=path.stem)


def _sort_key(page: Page) -> tuple[bool, int, str]:
    return (page.nav_order is None, page.nav_order or 0, page.title.lower())


def list_section(docs: Path, folder: str) -> list[Page]:
    directory = docs / folder
    if not directory.is_dir():
        return []
    pages: list[Page] = []
    for path in directory.glob("*.md"):
        if path.name in SKIP_NAMES:
            continue
        pages.append(parse_page(path, docs))
    pages.sort(key=_sort_key)
    return pages


def scan_docs(docs: Path) -> dict[str, list[Page]]:
    return {folder: list_section(docs, folder) for folder, _title in SECTIONS}


def render_index_markdown(
    title: str,
    intro: str,
    pages: list[Page],
    link_prefix: str,
) -> str:
    lines = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        intro,
        "",
        "| Guide |",
        "| --- |",
    ]
    for page in pages:
        filename = Path(page.rel).name
        href = f"{link_prefix}{filename}" if link_prefix else filename
        lines.append(f"| [{page.title}]({href}) |")
    lines.append("")
    return "\n".join(lines)


def render_home_markdown(docs: Path) -> str:
    scanned = scan_docs(docs)
    lines = [
        GENERATED_MARKER,
        "",
        "# Awesome Ads",
        "",
        HOME_INTRO,
        "",
    ]
    for folder, title in SECTIONS:
        pages = scanned[folder]
        lines.append(f"## {title}")
        lines.append("")
        lines.append(SECTION_INTROS[folder])
        lines.append("")
        lines.append("| Guide |")
        lines.append("| --- |")
        for page in pages:
            lines.append(f"| [{page.title}]({page.rel}) |")
        lines.append("")
    lines.extend(
        [
            "## Contributing",
            "",
            "Human contributors should start with [Contributing](CONTRIBUTING.md) "
            "and [Community Guidelines](meta/COMMUNITY_GUIDELINES.md). "
            f"Automated agents should read the repository [AGENTS.md]({AGENTS_URL}) "
            "before editing.",
            "",
            "## License",
            "",
            f"Apache License 2.0. See [LICENSE]({LICENSE_URL}).",
            "",
        ]
    )
    return "\n".join(lines)


def mkdocs_nav(docs: Path) -> list:
    scanned = scan_docs(docs)
    nav: list = [{"Home": "index.md"}]
    for folder, title in SECTIONS:
        entries: list = [{title: f"{folder}/index.md"}]
        for page in scanned[folder]:
            entries.append({page.title: page.rel})
        nav.append({title: entries})
    nav.append({"Contributing": "CONTRIBUTING.md"})
    return nav
