#!/usr/bin/env python3
"""Filesystem catalog for the site nav and generated indexes."""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
import re

H1_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
NAV_ORDER_RE = re.compile(r"<!--\s*nav_order:\s*(-?\d+)\s*-->")
SKIP_NAMES = frozenset({"AGENTS.md", "README.md", "CONTRIBUTING.md", "index.md"})
GENERATED_MARKER = "<!-- Generated by scripts/prepare-mkdocs.py. Do not edit. -->"
BUILD_CONFIG = "mkdocs.gen.yml"

SECTIONS: tuple[tuple[str, str], ...] = (
    ("channels", "Channels"),
    ("resources", "Resources"),
    ("ad-templates", "Templates"),
    ("meta", "Meta"),
)

SECTION_INTROS: dict[str, str] = {
    "channels": "Guides for each major advertising channel, from setup through optimization.",
    "resources": "Cross-cutting topics that apply across channels.",
    "ad-templates": "Ad templates and design resources.",
    "meta": "Repository documentation and community policy.",
}

HOME_INTRO = """**A practical advertising playbook for small businesses.**

Awesome Ads is an open reference for planning, launching, and refining campaigns across digital and traditional channels. Each guide stands on its own: read cover to cover or jump straight to the channel you need."""

HOME_START = """## Where to start

New to paid advertising? Read three guides before you pick a channel:

1. [Budgeting](resources/BUDGETING.md): how much to spend and how to split it when you have less than $5,000 a month.
2. [Analytics](resources/ANALYTICS.md): the metrics and tracking setup that tell you whether an ad paid for itself.
3. [Legal](resources/LEGAL.md): FTC endorsement and review rules, privacy laws, and CAN-SPAM, so your ads do not create a problem later.

Then choose one or two channels below and give them time to learn before you add more."""


LICENSE_URL = "https://github.com/TMHSDigital/Awesome-Ads/blob/main/LICENSE"
AGENTS_URL = "https://github.com/TMHSDigital/Awesome-Ads/blob/main/AGENTS.md"


@dataclass(frozen=True)
class Page:
    rel: str
    title: str
    nav_order: int | None
    stem: str
    summary: str = ""


def parse_page(path: Path, docs: Path) -> Page:
    text = path.read_text(encoding="utf-8")
    heading = H1_RE.search(text)
    if heading is None:
        raise ValueError(f"{path} has no H1")
    order_match = NAV_ORDER_RE.search(text)
    nav_order = int(order_match.group(1)) if order_match else None
    rel = path.relative_to(docs).as_posix()
    return Page(
        rel=rel,
        title=heading.group(1).strip(),
        nav_order=nav_order,
        stem=path.stem,
        summary=first_sentence(text),
    )


def _guide_line(page: Page, href: str) -> str:
    if page.summary:
        return f"- [{page.title}]({href}): {page.summary}"
    return f"- [{page.title}]({href})"


_COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
_FRONT_MATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)
_LINK_RE = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")
_EMPHASIS_RE = re.compile(r"(\*\*|__|\*|`)")
_PROSE_START_RE = re.compile(r"^[A-Za-z0-9*_\[\"']")


def first_paragraph(markdown: str) -> str:
    """Return the first prose paragraph as plain text, or an empty string."""
    text = _FRONT_MATTER_RE.sub("", markdown.replace("\r\n", "\n"))
    text = _COMMENT_RE.sub("", text)
    for block in re.split(r"\n\s*\n", text):
        block = block.strip()
        if not block or not _PROSE_START_RE.match(block):
            continue
        plain = _LINK_RE.sub(r"\1", block)
        plain = _EMPHASIS_RE.sub("", plain)
        return " ".join(plain.split())
    return ""


_SENTENCE_END_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z])")


def first_sentence(markdown: str) -> str:
    """First sentence of the first prose paragraph."""
    return _SENTENCE_END_RE.split(first_paragraph(markdown), maxsplit=1)[0]


def _sort_key(page: Page) -> tuple[bool, int, str]:
    return (page.nav_order is None, page.nav_order or 0, page.title.lower())


def list_section(docs: Path, folder: str) -> list[Page]:
    directory = docs / folder
    if not directory.is_dir():
        return []
    pages: list[Page] = []
    for path in directory.glob("*.md"):
        if path.name in SKIP_NAMES:
            continue
        pages.append(parse_page(path, docs))
    pages.sort(key=_sort_key)
    return pages


def scan_docs(docs: Path) -> dict[str, list[Page]]:
    return {folder: list_section(docs, folder) for folder, _title in SECTIONS}


def generated_doc_paths() -> tuple[str, ...]:
    """Return the repo-relative paths written by prepare-mkdocs.py."""
    return (
        "docs/index.md",
        "docs/CONTRIBUTING.md",
        *(f"docs/{folder}/index.md" for folder, _title in SECTIONS),
    )


def render_index_markdown(
    title: str,
    intro: str,
    pages: list[Page],
    link_prefix: str,
) -> str:
    lines = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        intro,
        "",
    ]
    for page in pages:
        filename = Path(page.rel).name
        href = f"{link_prefix}{filename}" if link_prefix else filename
        lines.append(_guide_line(page, href))
    lines.append("")
    return "\n".join(lines)


def render_home_markdown(docs: Path) -> str:
    scanned = scan_docs(docs)
    lines = [
        GENERATED_MARKER,
        "",
        "# Awesome Ads",
        "",
        HOME_INTRO,
        "",
        HOME_START,
        "",
    ]
    for folder, title in SECTIONS:
        pages = scanned[folder]
        lines.append(f"## {title}")
        lines.append("")
        lines.append(SECTION_INTROS[folder])
        lines.append("")
        for page in pages:
            lines.append(_guide_line(page, page.rel))
        lines.append("")
    lines.extend(
        [
            "## Contributing",
            "",
            "Human contributors should start with [Contributing](CONTRIBUTING.md) "
            "and [Community Guidelines](meta/COMMUNITY_GUIDELINES.md). "
            f"Automated agents should read the repository [AGENTS.md]({AGENTS_URL}) "
            "before editing.",
            "",
            "## License",
            "",
            f"Apache License 2.0. See [LICENSE]({LICENSE_URL}).",
            "",
        ]
    )
    return "\n".join(lines)


def mkdocs_nav(docs: Path) -> list:
    scanned = scan_docs(docs)
    nav: list = [{"Home": "index.md"}]
    for folder, title in SECTIONS:
        entries: list = [{title: f"{folder}/index.md"}]
        for page in scanned[folder]:
            entries.append({page.title: page.rel})
        nav.append({title: entries})
    nav.append({"Contributing": "CONTRIBUTING.md"})
    return nav


def render_build_config(base: str, nav: list) -> str:
    """Return the build config: the base mkdocs.yml text plus an explicit nav.

    Zensical does not run MkDocs hooks, so the sidebar order from the catalog
    is written into the config instead. JSON is valid YAML flow syntax.
    """
    header = "# Generated by scripts/prepare-mkdocs.py from mkdocs.yml. Do not edit.\n"
    body = base.replace("\r\n", "\n").rstrip("\n")
    return f"{header}{body}\n\nnav: {json.dumps(nav, ensure_ascii=False)}\n"
